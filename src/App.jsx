import React, { useState, useEffect } from 'react';
import { Routes, Route, Navigate } from 'react-router-dom';
import Header from './components/Header';
import Sidebar from './components/Sidebar';
import Dashboard from './pages/Dashboard';
import History from './pages/History';
import Settings from './pages/Settings';

function App() {
  const [simulatorMode, setSimulatorMode] = useState(
    localStorage.getItem('simulatorMode') === 'true'
  );
  
  const [accessToken, setAccessToken] = useState(null);
  const [playlists, setPlaylists] = useState([]);
  const [loading, setLoading] = useState(false);
  const [isExecuting, setIsExecuting] = useState(false);
  const [progress, setProgress] = useState("");
  const [searchQuery, setSearchQuery] = useState("");
  const [fetchTrigger, setFetchTrigger] = useState(0);
  const [theme, setTheme] = useState(
    localStorage.getItem('theme') || 'system'
  );
  
  const [modalConfig, setModalConfig] = useState(null);

  const triggerModal = (config) => {
    setModalConfig(config);
  };

  const refetchPlaylists = () => {
    setFetchTrigger(prev => prev + 1);
  };

  // Sync simulatorMode and auto-authenticate with mock token if active
  useEffect(() => {
    localStorage.setItem('simulatorMode', simulatorMode.toString());
    if (simulatorMode && !accessToken) {
      setAccessToken('mock_access_token');
    } else if (!simulatorMode && accessToken === 'mock_access_token') {
      setAccessToken(null);
    }
  }, [simulatorMode]);

  useEffect(() => {
    const mediaQuery = window.matchMedia('(prefers-color-scheme: dark)');
    
    const applyTheme = () => {
      if (theme === 'light') {
        document.body.classList.add('light-theme');
      } else if (theme === 'dark') {
        document.body.classList.remove('light-theme');
      } else {
        if (mediaQuery.matches) {
          document.body.classList.remove('light-theme');
        } else {
          document.body.classList.add('light-theme');
        }
      }
    };

    applyTheme();
    localStorage.setItem('theme', theme);

    const handleSystemChange = () => {
      if (theme === 'system') {
        applyTheme();
      }
    };

    mediaQuery.addEventListener('change', handleSystemChange);
    return () => mediaQuery.removeEventListener('change', handleSystemChange);
  }, [theme]);

  // Fetch Playlists (Mocked if simulatorMode is active)
  useEffect(() => {
    if (!accessToken) {
      setPlaylists([]);
      return;
    }

    const fetchPlaylists = async () => {
      setLoading(true);
      try {
        if (simulatorMode) {
          // Simulate network delay
          await new Promise(r => setTimeout(r, 800));
          
          // Provide standard sandbox mock playlists
          const mockPlaylists = [
            {
              id: 'mock_rare_songs',
              title: 'rare songs',
              description: 'Playlist with emoji suffix',
              videos: 14,
              thumbnail: 'https://images.unsplash.com/photo-1514525253161-7a46d19cd819?w=120&auto=format&fit=crop&q=60',
              ignore: false,
              publishedAt: new Date(Date.now() - 365*24*60*60*1000).toISOString()
            },
            {
              id: 'mock_cs_tech',
              title: 'Computer Science 💻',
              description: 'Programming tutorials',
              videos: 11,
              thumbnail: 'https://images.unsplash.com/photo-1517694712202-14dd9538aa97?w=120&auto=format&fit=crop&q=60',
              ignore: false,
              publishedAt: new Date(Date.now() - 120*24*60*60*1000).toISOString()
            },
            {
              id: 'mock_fitness',
              title: 'Gym Workout Motivation',
              description: 'Aggressive grind beats',
              videos: 8,
              thumbnail: 'https://images.unsplash.com/photo-1517838277536-f5f99be501cd?w=120&auto=format&fit=crop&q=60',
              ignore: false,
              publishedAt: new Date(Date.now() - 60*24*60*60*1000).toISOString()
            },
            {
              id: 'mock_trippy',
              title: 'Trippy Visuals and Live Sets',
              description: 'Auto-generated by Organizer',
              videos: 15,
              thumbnail: 'https://images.unsplash.com/photo-1506157786151-b8491531f063?w=120&auto=format&fit=crop&q=60',
              ignore: false,
              publishedAt: new Date(Date.now() - 10*24*60*60*1000).toISOString()
            }
          ];
          
          const savedProtectedIds = JSON.parse(localStorage.getItem('protectedPlaylistIds')) || [];
          const formatted = mockPlaylists.map(item => ({
            ...item,
            ignore: savedProtectedIds.includes(item.id)
          }));

          setPlaylists(formatted);
          setLoading(false);
          return;
        }

        // Live API Fetch
        let allPlaylists = [];
        let pageToken = '';
        do {
          const response = await fetch(
            `https://www.googleapis.com/youtube/v3/playlists?part=snippet,contentDetails&mine=true&maxResults=50${pageToken ? '&pageToken=' + pageToken : ''}`,
            { headers: { Authorization: `Bearer ${accessToken}`, Accept: 'application/json' } }
          );
          const data = await response.json();
          if (data.items) allPlaylists = [...allPlaylists, ...data.items];
          pageToken = data.nextPageToken;
        } while (pageToken);

        const savedProtectedIds = JSON.parse(localStorage.getItem('protectedPlaylistIds')) || [];

        const formatted = allPlaylists.map(item => {
          const title = item.snippet.title;
          const description = item.snippet.description || '';
          const shouldIgnore = savedProtectedIds.includes(item.id);

          return {
            id: item.id,
            title: title,
            description: description,
            videos: item.contentDetails.itemCount,
            thumbnail: item.snippet.thumbnails?.medium?.url || '',
            ignore: shouldIgnore,
            publishedAt: item.snippet.publishedAt || ''
          };
        });
        setPlaylists(formatted);
      } catch (error) {
        console.error("Error fetching playlists:", error);
      }
      setLoading(false);
    };
    fetchPlaylists();
  }, [accessToken, fetchTrigger, simulatorMode]);

  // Persist protected playlist IDs to localStorage
  useEffect(() => {
    if (playlists.length > 0) {
      const protectedIds = playlists.filter(p => p.ignore).map(p => p.id);
      localStorage.setItem('protectedPlaylistIds', JSON.stringify(protectedIds));
    }
  }, [playlists]);

  return (
    <div className="app-container">
      {/* Simulator Mode Warning Banner */}
      {simulatorMode && (
        <div style={{ backgroundColor: '#e67e22', color: '#fff', textAlign: 'center', padding: '6px', fontSize: '12px', fontWeight: 'bold', letterSpacing: '0.5px' }}>
          DEVELOPER SANDBOX MODE IS ACTIVE. ALL GOOGLE ACTIONS ARE MOCKED.
        </div>
      )}

      {/* Dynamic Unified Modal Backdrop */}
      {modalConfig && (
        <div className="modal-backdrop" onClick={() => { if (modalConfig.type !== 'prompt') setModalConfig(null); }}>
          <div className="modal-content" onClick={(e) => e.stopPropagation()}>
            <h3 style={{ marginBottom: '12px', color: 'var(--yt-spec-text-primary)' }}>{modalConfig.title}</h3>
            {modalConfig.message && (
              <p style={{ fontSize: '14px', color: 'var(--yt-spec-text-secondary)', marginBottom: '20px', lineHeight: '1.5', whiteSpace: 'pre-line' }}>
                {modalConfig.message}
              </p>
            )}
            
            {modalConfig.type === 'prompt' && (
              <input 
                type="text" 
                className="search-input" 
                placeholder={modalConfig.placeholder || ""}
                defaultValue={modalConfig.defaultValue || ""}
                id="modal-prompt-input"
                style={{ width: '100%', marginBottom: '20px', borderRadius: '4px', height: '36px' }}
                onKeyDown={(e) => {
                  if (e.key === 'Enter') {
                    const currentConfig = modalConfig;
                    const val = document.getElementById('modal-prompt-input')?.value;
                    setModalConfig(null);
                    if (currentConfig.onConfirm) currentConfig.onConfirm(val);
                  }
                }}
              />
            )}
            
            <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '8px' }}>
              {modalConfig.type !== 'alert' && (
                <button 
                  className="btn-primary" 
                  style={{ backgroundColor: '#555' }}
                  onClick={() => {
                    const currentConfig = modalConfig;
                    setModalConfig(null);
                    if (currentConfig.onCancel) currentConfig.onCancel();
                  }}
                >
                  Cancel
                </button>
              )}
              <button 
                className="btn-primary"
                onClick={() => {
                  const currentConfig = modalConfig;
                  const val = currentConfig.type === 'prompt' 
                    ? document.getElementById('modal-prompt-input')?.value 
                    : null;
                  setModalConfig(null);
                  if (currentConfig.type === 'prompt') {
                    if (currentConfig.onConfirm) currentConfig.onConfirm(val);
                  } else {
                    if (currentConfig.onConfirm) currentConfig.onConfirm();
                  }
                }}
              >
                {modalConfig.confirmText || "OK"}
              </button>
            </div>
          </div>
        </div>
      )}

      <Header 
        onLogin={setAccessToken} 
        isLoggedIn={!!accessToken} 
        onLogout={() => setAccessToken(null)}
        searchQuery={searchQuery}
        setSearchQuery={setSearchQuery}
      />
      {(loading || isExecuting) && (
        <div className="loading-bar-container">
          <div className="loading-bar-active"></div>
        </div>
      )}
      <div className="main-layout">
        <Sidebar isLoggedIn={!!accessToken} />
        <main className="content-area">
          <Routes>
            <Route path="/" element={
              <Dashboard 
                accessToken={accessToken} 
                playlists={playlists}
                setPlaylists={setPlaylists}
                loading={loading}
                isExecuting={isExecuting}
                setIsExecuting={setIsExecuting}
                progress={progress}
                setProgress={setProgress}
                triggerModal={triggerModal}
                searchQuery={searchQuery}
                refetchPlaylists={refetchPlaylists}
                simulatorMode={simulatorMode}
              />
            } />
            <Route path="/history" element={
              accessToken ? (
                <History 
                  accessToken={accessToken} 
                  triggerModal={triggerModal} 
                  refetchPlaylists={refetchPlaylists} 
                  isExecuting={isExecuting}
                  setIsExecuting={setIsExecuting}
                  progress={progress}
                  setProgress={setProgress}
                  simulatorMode={simulatorMode}
                />
              ) : <Navigate to="/" />
            } />
            <Route path="/settings" element={
              accessToken ? (
                <Settings 
                  theme={theme} 
                  setTheme={setTheme} 
                  accessToken={accessToken}
                  playlists={playlists}
                  setPlaylists={setPlaylists}
                  isExecuting={isExecuting}
                  setIsExecuting={setIsExecuting}
                  progress={progress}
                  setProgress={setProgress}
                  triggerModal={triggerModal}
                  simulatorMode={simulatorMode}
                  setSimulatorMode={setSimulatorMode}
                />
              ) : <Navigate to="/" />
            } />
          </Routes>
        </main>
      </div>
    </div>
  );
}

export default App;
